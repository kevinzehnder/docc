func TestGradePerfectTranscription(t *testing.T) {
	src := "Die vorliegende Eingabe erfolgt innert Frist."
	s := Grade(Transcription{Markdown: src, SourceText: src})

	if !s.HasText {
		t.Fatal("HasText = false for a document with a source text")
	}
	if s.F1 != 1 {
		t.Errorf("F1 = %v, want 1 for an identical transcription (missing %v, spurious %v)", s.F1, s.Missing, s.Spurious)
	}
}

// Punctuation and case are not OCR errors worth counting: models normalise
// quotation marks and sentence spacing differently and none of it changes what
// the document says.
func TestGradeIgnoresPunctuationAndCase(t *testing.T) {
	s := Grade(Transcription{
		SourceText: `Die Beklagte gibt die «Rechtsprechung» wieder.`,
		Markdown:   `Die Beklagte gibt die "Rechtsprechung" wieder`,
	})
	if s.F1 != 1 {
		t.Errorf("F1 = %v, want 1 (missing %v, spurious %v)", s.F1, s.Missing, s.Spurious)
	}
}

// Umlauts and ß have to survive the comparison, or a transcription that
// silently transliterates them would score as perfect.
func TestGradeCountsTransliterationAsAnError(t *testing.T) {
	s := Grade(Transcription{
		SourceText: "Die Ausführungen der Beklagten betreffen die Grösse",
		Markdown:   "Die Ausfuehrungen der Beklagten betreffen die Grosse",
	})
	if s.F1 == 1 {
		t.Error("a transliterated transcription scored as perfect")
	}
	if !contains(s.Missing, "ausführungen") {
		t.Errorf("Missing = %v, want it to name the word that was transliterated", s.Missing)
	}
}

func TestGradeReportsMissingAndSpuriousWords(t *testing.T) {
	s := Grade(Transcription{
		SourceText: "Erste Erwägung zur Streitwertberechnung",
		Markdown:   "Erste Erwägung zur Streitwertberechnungx erfunden",
	})
	if s.Recall == 1 {
		t.Error("recall = 1 although a word was dropped")
	}
	if s.Precision == 1 {
		t.Error("precision = 1 although a word was invented")
	}
	if !contains(s.Spurious, "erfunden") {
		t.Errorf("Spurious = %v, want it to name the invented word", s.Spurious)
	}
}

// A scan has no text layer, so the word scores mean nothing and must not be
// reported as a perfect result.
func TestGradeWithoutSourceTextSkipsWordScores(t *testing.T) {
	s := Grade(Transcription{Markdown: "[Rz 1] Erste Erwägung."})
	if s.HasText {
		t.Error("HasText = true without a source text")
	}
	if s.F1 != 0 {
		t.Errorf("F1 = %v, want 0 when there is nothing to compare against", s.F1)
	}
	if s.RandzifferFound != 1 {
		t.Errorf("structural scores must still work: RandzifferFound = %d, want 1", s.RandzifferFound)
	}
}

func TestGradeCountsSequenceBreaks(t *testing.T) {
	md := strings.Join([]string{
		"[Rz 1] Erste.",
		"[Rz 2] Zweite.",
		"[Rz 7] Nach einer Lücke.", // a gap: a page was lost
		"[Rz 8] Weiter.",
		"[Rz 8] Wiederholt.", // a repeat: two paragraphs merged
	}, "\n\n")

	s := Grade(Transcription{Markdown: md})
	if s.RandzifferFound != 5 {
		t.Errorf("RandzifferFound = %d, want 5", s.RandzifferFound)
	}
	if s.SequenceBreaks != 2 {
		t.Errorf("SequenceBreaks = %d, want 2 (one gap, one repeat)", s.SequenceBreaks)
	}
}

func TestGradeCountsLeakedFurniture(t *testing.T) {
	md := strings.Join([]string{
		"Luchsinger + Spinner",
		"",
		"[Rz 1] Erste Erwägung.",
		"",
		"- 5 -",
		"",
		"[Rz 2] Zweite Erwägung.",
		"",
		"6",
	}, "\n")

	s := Grade(Transcription{Markdown: md, Letterhead: "Luchsinger + Spinner"})
	if s.PageNumbers != 2 {
		t.Errorf("PageNumbers = %d, want 2 (\"- 5 -\" and a bare \"6\")", s.PageNumbers)
	}
	if s.Letterheads != 1 {
		t.Errorf("Letterheads = %d, want 1", s.Letterheads)
	}
}

// A number inside a sentence is not a leaked page number.
func TestGradeDoesNotCountNumbersInProse(t *testing.T) {
	s := Grade(Transcription{Markdown: "[Rz 1] Die Frist von 30 Tagen läuft ab."})
	if s.PageNumbers != 0 {
		t.Errorf("PageNumbers = %d, want 0", s.PageNumbers)
	}
}

func TestPlainTextStripsWhatThePageNeverShows(t *testing.T) {
	src := strings.Join([]string{
		"---",
		"docc: 1",
		"document_type: legal",
		"---",
		"",
		"<!-- generated by `docc ingest` from x.pdf -->",
		"",
		"# RECHTSBEGEHREN",
		"",
		"Es sei festzustellen, dass die Kündigung nichtig ist.",
		"",
		"::: beweis",
		"",
		"- [Beilage 3] Mietvertrag vom 03./07.09.2001",
		":::",
	}, "\n")

	got := PlainText(src)
	for _, gone := range []string{"document_type", "docc: 1", "generated by", ":::"} {
		if strings.Contains(got, gone) {
			t.Errorf("PlainText kept %q, which never appears on the page:\n%s", gone, got)
		}
	}
	for _, kept := range []string{"RECHTSBEGEHREN", "Kündigung nichtig", "Mietvertrag vom 03./07.09.2001"} {
		if !strings.Contains(got, kept) {
			t.Errorf("PlainText dropped %q, which does appear on the page:\n%s", kept, got)
		}
	}
}

// A round trip can predict the numbering because docc generates it by the same
// rule the schema states: prose paragraphs after a named heading, and nothing
// else.
func TestExpectedRandziffern(t *testing.T) {
	src := strings.Join([]string{
		"# RECHTSBEGEHREN",
		"",
		"Nicht nummeriert, weil vor der Startüberschrift.",
		"",
		"# BEGRÜNDUNG",
		"",
		"Erster nummerierter Absatz.",
		"",
		"## Zuständigkeit",
		"",
		"Zweiter nummerierter Absatz.",
		"",
		"- ein Listeneintrag",
		"- noch einer",
		"",
		"::: beweis",
		"",
		"- [Beilage 1] Ein Beweismittel",
		":::",
		"",
		"Dritter nummerierter Absatz.",
	}, "\n")

	if got := ExpectedRandziffern(src, "BEGRÜNDUNG"); got != 3 {
		t.Errorf("ExpectedRandziffern = %d, want 3 — headings, list items and fenced blocks are not body prose", got)
	}
	// With no start heading the whole body counts.
	if got := ExpectedRandziffern(src, ""); got != 4 {
		t.Errorf("ExpectedRandziffern with no start heading = %d, want 4", got)
	}
}

func contains(words []string, want string) bool {
	for _, w := range words {
		if w == want {
			return true
		}
	}
	return false
}

// A brief's court address, parties and signature come from frontmatter and are
// rendered onto the page, so a round trip that scores only the body counts
// every one of them as invented.
func TestFlattenValues(t *testing.T) {
	got := FlattenValues(map[string]any{
		"case_ref": "ZG.2026.014",
		"gericht": map[string]any{
			"name":        "Bezirksgericht Baden",
			"postal_code": "5400",
		},
		"beilagen":            []any{"Werkvertrag vom 3. März 2024"},
		"beklagter_vertreter": nil,
	})

	for _, want := range []string{"ZG.2026.014", "Bezirksgericht Baden", "5400", "Werkvertrag"} {
		if !strings.Contains(got, want) {
			t.Errorf("FlattenValues dropped %q, which the theme renders onto the page:\n%s", want, got)
		}
	}
	if strings.Contains(got, "<nil>") {
		t.Errorf("a nullable field rendered as a literal nil:\n%s", got)
	}
}

// The word scores discard "#" along with every other non-letter, so a model
// that writes headings as plain text scores exactly as well as one that marks
// them up. Downstream that is the difference between a draft docc can check and
// one that fails every section rule, so it is counted separately.
func TestGradeCountsHeadings(t *testing.T) {
	md := strings.Join([]string{
		"# RECHTSBEGEHREN",
		"",
		"Es sei festzustellen.",
		"",
		"## Zuständigkeit",
		"",
		"Das Gericht ist zuständig.",
	}, "\n")

	s := Grade(Transcription{Markdown: md, SourceHeadings: 3})
	if s.HeadingsFound != 2 {
		t.Errorf("HeadingsFound = %d, want 2", s.HeadingsFound)
	}
	if s.HeadingsExpected != 3 {
		t.Errorf("HeadingsExpected = %d, want 3", s.HeadingsExpected)
	}

	// The same text with the markup dropped scores the same on words and must
	// not score the same here.
	flat := Grade(Transcription{Markdown: strings.ReplaceAll(md, "#", ""), SourceHeadings: 3})
	if flat.HeadingsFound != 0 {
		t.Errorf("HeadingsFound = %d for a transcription with no markup, want 0", flat.HeadingsFound)
	}
}
